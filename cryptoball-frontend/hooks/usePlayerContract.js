const contractAddress = '0x5FbDB2315678afecb367f032d93F642f64180aa3';

export const usePlayerContract = () => {
    const [provider, setProvider] = useState(null);
    const [playerContract, setPlayerContract] = useState(null);
    const [attributes, setAttributes] = useState({});
    const [gamesLeft, setGamesLeft] = useState(100);
    const [goals, setGoals] = useState(0);
    const [id, setId] = useState(0);
    
    useEffect(() => {
        const initContract = async () => {
            if (window.ethereum) {
                try {
                    await window.ethereum.request({ method: 'eth_requestAccounts' });
                    const provider = new ethers.BrowserProvider(window.ethereum);
                    const signer = provider.getSigner();
                    const playerContract = new ethers.Contract(contractAddress, contractABI, signer);
                    setPlayerContract(playerContract);
                } catch (error) {
                    console.error('Error connecting to MetaMask:', error);
                }
            } else {
                console.error('Ethereum object not found, install MetaMask.');
            }
        };

        initContract();
    }, []);

    const getPlayerAttributes = async (id) => {
        if (!playerContract) return;
        const attributes = await playerContract.getPlayerAttributes(id);
        setAttributes(attributes);
    };

    // const getAllPlayers = async () => {
    //     if (!playerContract) return;
    //     const score = await playerContract.getAllPlayers();
    //     setScore(score);
    // };

    const getGamesLeft = async (id) => {
        if (!playerContract) return;
        const gamesLeft = await playerContract.getGamesLeft(id);
        setGamesLeft(gamesLeft);
    }

    const getGoals = async (id) => {
        if (!playerContract) return;
        const goals = await playerContract.getGoals(id);
        setGoals(goals);
    }

    const mintPlayer = async () => {
        if (!playerContract) return;
        const id = await playerContract.mintPlayer('0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266');
        setId(id);
    }

    return { getPlayerAttributes, getGoals, getPlayerAttributes, getGamesLeft, mintPlayer };
};